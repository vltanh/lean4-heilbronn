#!/usr/bin/env python3
"""Export the searched cover trees (pickle from run_pairs.py) to Lean chunk modules and data files.

usage: export.py TREES.pkl [MAXTERMS] [--partial]
Writes data/nine/seven_b/cNNNN.txt, Heilbronn/Nine/SevenBoundary/Interior/Trees/ChunkN.lean and
Heilbronn/Nine/SevenBoundary/Interior/Trees.lean. Every certificate is re-checked exactly before writing.
The case order is the one of order.json (written by the first export; kept so that already
checked chunks stay identical), then the remaining keys. --partial skips missing trees.

Pipeline: run_pairs.py TREES.pkl NPROC searches every case of engine.case_keys() (engine.solve);
run_hard2.py KEYS OUT.pkl searches one hard case with engine.solve2 (the two cases [22, 44] and
[24, 39] needed it); merge the pickles, then export.py.
"""
import sys, pickle, shutil
from pathlib import Path
import engine as G
from certlib import check, write_terms

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / 'data' / 'nine' / 'seven_b'
LEAN = ROOT / 'Heilbronn' / 'Nine' / 'SevenBoundary' / 'Interior' / 'Trees'
REL = '../../../../../data/nine/seven_b'


def verify(ks, facts, t):
    if t[0] == 'cert':
        assert check(G.atoms(ks, facts), t[1]), (ks, facts)
        return
    for n, c in enumerate(t[-1]):
        if t[0] == 'tri':
            f = facts + [('s', (t[1], n == 1))]
        else:
            f = facts + ([('c', G.k(t[2]) - G.v(t[1]))] if n == 0 else [('c', G.v(t[1]) - G.k(t[2]))])
        verify(ks, f, c)


def emit(t, counter):
    if t[0] == 'cert':
        fn = 'c%04d.txt' % counter[0]
        counter[0] += 1
        write_terms(str(DATA / fn), t[1])
        return '.cert (term_rows%% "%s/%s")' % (REL, fn)
    kids = ', '.join(emit(c, counter) for c in t[-1])
    if t[0] == 'tri':
        return '.node (.tri %d %d %d) [%s]' % (*t[1], kids)
    return '.node (.cut %d %s) [%s]' % (t[1], G.qlean(t[2]), kids)


def main():
    trees = pickle.load(open(sys.argv[1], 'rb'))
    maxterms = int(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2].isdigit() else 2500
    singles, pairs = G.case_keys()
    keys = singles + pairs
    # stable order: the keys of order.json first (chunks already checked), then the others
    import json, os
    of = Path(__file__).with_name('order.json')
    if of.exists():
        pre = [k for k in json.load(open(of)) if k in keys]
        keys = pre + [k for k in keys if k not in pre]
    missing = [ks for ks in keys if trees.get(tuple(ks)) is None]
    if '--partial' in sys.argv:
        keys = [ks for ks in keys if ks not in missing]
    else:
        assert not missing, missing
    for ks in keys:
        verify(ks, [], trees[tuple(ks)])
    if not of.exists():
        json.dump(keys, open(of, 'w'))
    if DATA.exists():
        shutil.rmtree(DATA)
    DATA.mkdir(parents=True)
    if LEAN.exists():
        shutil.rmtree(LEAN)
    LEAN.mkdir(parents=True)
    chunks, cur, curterms = [], [], 0
    for ks in keys:
        n = G.tree_terms(trees[tuple(ks)])
        if cur and curterms + n > maxterms:
            chunks.append(cur); cur, curterms = [], 0
        cur.append(ks); curterms += n
    if cur:
        chunks.append(cur)
    counter = [0]
    for ci, ch in enumerate(chunks):
        nterms = sum(G.tree_terms(trees[tuple(ks)]) for ks in ch)
        defs = []
        for ti, ks in enumerate(ch):
            body = emit(trees[tuple(ks)], counter)
            defs.append('/-- The tree of the case %s. -/\nnoncomputable def tree%d_%d : Cover.Tree Split :=\n  %s\n'
                        % (ks, ci, ti, body))
        lst = ',\n    '.join('(%s, tree%d_%d)' % (ks, ci, ti) for ti, ks in enumerate(ch))
        src = '''module

public import Heilbronn.Nine.SevenBoundary.Interior.Model
public import Heilbronn.Common.DataReader

/-! # Seven-boundary interior cover, chunk %d (generated by `scripts/nine/seven_b/export.py`)

The trees of %d cases (%d certificate terms), checked by the kernel. -/

@[expose] public section

namespace Heilbronn.Nine.SevenInterior.Trees

open Cover Model

%s
/-- The cases of chunk %d with their trees. -/
noncomputable def chunk%d : List (List ℕ × Cover.Tree Split) :=
  [%s]

theorem chunk%d_ok : chunk%d.all (fun p => checkTree (spec p.1) [] p.2) = true := by
  decide +kernel

end Heilbronn.Nine.SevenInterior.Trees
''' % (ci, len(ch), nterms, '\n'.join(defs), ci, ci, lst, ci, ci)
        (LEAN / ('Chunk%d.lean' % ci)).write_text(src)
    imports = '\n'.join('public import Heilbronn.Nine.SevenBoundary.Interior.Trees.Chunk%d' % i for i in range(len(chunks)))
    cat = ' ++ '.join('chunk%d' % i for i in range(len(chunks)))
    oks = ', '.join('chunk%d_ok' % i for i in range(len(chunks)))
    keystr = ',\n    '.join(str(ks) for ks in keys)
    src = '''module

%s

/-! # Seven-boundary interior cover: all cases (generated by `scripts/nine/seven_b/export.py`)

The trees of the %d cases (%d single-point, %d pairs), collected from the chunks
`Heilbronn.Nine.SevenInterior.Trees.ChunkN`, each checked there by the kernel. -/

@[expose] public section

namespace Heilbronn.Nine.SevenInterior.Trees

open Cover Model

/-- All the cases with their trees. -/
noncomputable def allCases : List (List ℕ × Cover.Tree Split) :=
  %s

theorem allCases_ok : ∀ p ∈ allCases, checkTree (spec p.1) [] p.2 = true := by
  intro p hp
  have h : allCases.all (fun p => checkTree (spec p.1) [] p.2) = true := by
    simp only [allCases, List.all_append, %s, Bool.and_self]
  exact List.all_eq_true.1 h p hp

/-- The cases covered. -/
def caseKeys : List (List ℕ) :=
  [%s]

theorem caseKeys_eq : allCases.map Prod.fst = caseKeys := by decide +kernel

end Heilbronn.Nine.SevenInterior.Trees
''' % (imports, len(keys), len(singles), len(pairs), cat, oks, keystr)
    (LEAN.parent / 'Trees.lean').write_text(src)
    print('chunks', len(chunks), 'certs', counter[0],
          'terms', sum(G.tree_terms(trees[tuple(ks)]) for ks in keys))


if __name__ == '__main__':
    main()
