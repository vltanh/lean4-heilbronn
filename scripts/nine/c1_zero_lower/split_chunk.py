#!/usr/bin/env python3
"""Split a one-case zero-lower tree chunk into small kernel checks.

usage: split_chunk.py N [LIMIT]

Rewrites Heilbronn/Nine/C1/ZeroLowerTrees/ChunkN.lean. Every subtree with more than LIMIT certificate
terms (default 2000) whose root is a sign split `.node (.tri a b c) [neg, pos]` is split at that
root; each remaining part gets its own kernel check (module ChunkN_k), and ChunkN recombines them
with `checkTree_tri_node` (ZeroLowerTrees/Split.lean). The names tree{N}_0, chunk{N} and
chunk{N}_ok are kept, so ZeroLowerTrees.lean is unchanged.
"""
import re, sys
from pathlib import Path

N = int(sys.argv[1])
LIMIT = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
root = Path(__file__).resolve().parents[3]
d = root / 'Heilbronn/Nine/C1/ZeroLowerTrees'
src = (d / f'Chunk{N}.lean').read_text()
assert src.count('noncomputable def tree') == 1, 'only one-case chunks are handled'
m = re.search(r'/-- The sign tree of the case (\[[0-9, ]+\])\. -/\nnoncomputable def tree%d_0 : '
              r'Cover.Tree Split :=\n  (.*)\n' % N, src)
case, body = m.group(1), m.group(2)


def parse(s, i=0):
    """Parse a tree at s[i:]; return (ast, next index). ast = ('node', split, [children]) | ('leaf', text)."""
    if s.startswith('.node (', i):
        j = s.index(')', i)
        split = s[i + 7:j]
        assert s[j + 1:j + 3] == ' [', s[j:j + 5]
        k = j + 3
        kids = []
        while True:
            t, k = parse(s, k)
            kids.append(t)
            if s[k] == ']':
                return ('node', split, kids), k + 1
            assert s.startswith(', ', k), s[k:k + 10]
            k += 2
    depth, j = 0, i
    while j < len(s):
        ch = s[j]
        if ch in '([':
            depth += 1
        elif ch in ')]':
            if depth == 0:
                break
            depth -= 1
        elif ch == ',' and depth == 0:
            break
        j += 1
    return ('leaf', s[i:j]), j


def text(t):
    return t[1] if t[0] == 'leaf' else '.node (%s) [%s]' % (t[1], ', '.join(text(c) for c in t[2]))


def size(t):
    if t[0] == 'leaf':
        n = 0
        for p in re.findall(r'term_rows% "([^"]+)"', t[1]):
            n += sum(1 for _ in open((d / p).resolve()))
        return n
    return sum(size(c) for c in t[2])


tree, end = parse(body)
assert end == len(body)
defs, leaves, combos = [], [], []   # leaves: (name, facts); combos: (name, a, b, c, facts, neg, pos)


def fact_list(fs):
    return '[' + ', '.join('((%d, %d, %d), %s)' % (a, b, c, 'true' if s else 'false') for a, b, c, s in fs) + ']'


def go(t, fs, name):
    if t[0] == 'node' and len(t[2]) == 2 and size(t) > LIMIT:
        r = re.fullmatch(r'\.tri (\d+) (\d+) (\d+)', t[1])
        if r:
            a, b, c = map(int, r.groups())
            if a < b < c < 9:
                go(t[2][0], fs + [(a, b, c, False)], name + 'n')
                go(t[2][1], fs + [(a, b, c, True)], name + 'p')
                defs.append((name, '.node (.tri %d %d %d) [%s, %s]' % (a, b, c, name + 'n', name + 'p')))
                combos.append((name, a, b, c, fs, name + 'n', name + 'p'))
                return
    defs.append((name, text(t)))
    leaves.append((name, fs, size(t)))


base = f'part{N}_'
go(tree, [], base)
ns = 'namespace Heilbronn.Nine.C1ZeroLower.Trees\n\nopen Cover Model\n'
head = 'module\n\npublic import Heilbronn.Nine.C1.ZeroLowerModel\npublic import Heilbronn.Common.DataReader\n'
out = [head, f'\n/-! # Zero-lower C1 cover, chunk {N}: the parts of the tree of the case {case}\n\nSplit by '
       '`scripts/nine/c1_zero_lower/split_chunk.py`. -/\n\n@[expose] public section\n\n', ns]
for name, t in defs:
    out.append(f'\nnoncomputable def {name} : Cover.Tree Split :=\n  {t}\n')
out.append('\nend Heilbronn.Nine.C1ZeroLower.Trees\n')
(d / f'Chunk{N}Defs.lean').write_text(''.join(out))
for i, (name, fs, sz) in enumerate(leaves):
    (d / f'Chunk{N}_{i}.lean').write_text(
        f'module\n\npublic import Heilbronn.Nine.C1.ZeroLowerTrees.Chunk{N}Defs\n\n'
        f'/-! # Zero-lower C1 cover, chunk {N}, part {i} ({sz} terms; kernel check) -/\n\n'
        f'@[expose] public section\n\n{ns}\ntheorem {name}ok :\n    checkTree (spec {case}) {fact_list(fs)} {name} = true := by\n'
        f'  decide +kernel\n\nend Heilbronn.Nine.C1ZeroLower.Trees\n')
imports = ''.join(f'public import Heilbronn.Nine.C1.ZeroLowerTrees.Chunk{N}_{i}\n' for i in range(len(leaves)))
body = [f'module\n\n{imports}public import Heilbronn.Nine.C1.ZeroLowerTrees.Split\n\n'
        f'/-! # Zero-lower C1 cover, chunk {N} (generated by `scripts/nine/c1_zero_lower/export.py`, split by\n'
        f'`scripts/nine/c1_zero_lower/split_chunk.py` into {len(leaves)} kernel checks)\n\nThe sign tree of the case {case}. -/\n\n'
        f'@[expose] public section\n\n{ns}']
for name, a, b, c, fs, n, p in combos:
    body.append(f'\ntheorem {name}ok :\n    checkTree (spec {case}) {fact_list(fs)} {name} = true :=\n'
                f'  checkTree_tri_node (by decide) {n}ok {p}ok\n')
body.append(f'''
/-- The sign tree of the case {case}. -/
noncomputable def tree{N}_0 : Cover.Tree Split := {base}

/-- The cases of chunk {N} with their trees. -/
noncomputable def chunk{N} : List (List ℕ × Cover.Tree Split) :=
  [({case}, tree{N}_0)]

theorem chunk{N}_ok : chunk{N}.all (fun p => checkTree (spec p.1) [] p.2) = true := by
  simp only [chunk{N}, List.all_cons, List.all_nil, Bool.and_true, tree{N}_0]
  exact {base}ok

end Heilbronn.Nine.C1ZeroLower.Trees
''')
(d / f'Chunk{N}.lean').write_text(''.join(body))
print('chunk', N, 'case', case, ':', len(leaves), 'parts', [s for _, _, s in leaves])
