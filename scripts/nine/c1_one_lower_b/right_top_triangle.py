#!/usr/bin/env python3
"""Export docs/proof/nine/c1_one_lower_right_top_triangle_certificates.json for Lean.

Mirror of Heilbronn/Nine/C1/OneLower/RightTopTriangleModel.lean: points O, C, R, D, X, F, H, L, P
(variables h, c, d, f, r_x, r_y, x_x, x_y, l_x, l_y, p_x, p_y = v 0..11), atoms
`factors ++ [q0] ++ costs(hullTable 7 [lower, cap])`. Every one of the 25 cells gets the first
certificate that applies to it (the checker's reuse rule), converted to integer weights over the
cell's Lean atoms, written to data/nine/c1_one_lower_rtt/cIJ.txt; the trees and their kernel check are
written to Heilbronn/Nine/C1/OneLower/RightTopTriangleTrees.lean.
"""
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import common as C  # noqa: E402
from common import v, k, N, SQ  # noqa: E402
import certlib  # noqa: E402
import check_c1_one_lower_right_top_triangle as Ck  # noqa: E402

ROOT = C.ROOT
DATA = ROOT / 'data' / 'nine' / 'c1_one_lower_rtt'
S = SQ


def pt(i):
    return {0: (N(0), N(0)), 1: (v(1), N(0)), 2: (v(4), v(5)), 3: (N(1), v(2)),
            4: (v(6), v(7)), 5: (v(3), N(1)), 6: (N(0), v(0)), 7: (v(8), v(9)),
            8: (v(10), v(11))}.get(i, (N(0), N(0)))


FACTORS = [
    v(0) - k(27 * S / 7), N(1) - v(0), v(1) - k(3 * S), k(F(7, 9)) - v(1),
    v(2) - k(4 * S), k(F(41, 65)) - v(2), v(3) - k(S), k(F(17, 41)) - v(3),
    v(0) - v(2), v(1) - v(3), v(2) - v(3), v(4) - v(1) - k(65 * S / 41), N(1) - v(4),
    v(5) - k(9 * S / 7), v(2) - v(5) - k(F(8, 49)),
    v(6) - v(3) - k(F(24, 41)), v(7) - v(2) - k(F(24, 65)), N(1) - v(6), N(1) - v(7),
    v(8) - k(S), v(9) - k(9 * S / 7), v(1) - v(8) - k(2 * S),
    v(0) - v(9) - k(18 * S / 7), N(1) - v(8) - v(9) - k(S),
    v(10) - v(3) - k(F(8, 41)), v(11) - v(2) - k(F(8, 65)),
    k(1 - S) - v(10), k(1 - S) - v(11)]
Q0 = (N(1) - v(2)) * (N(1) - v(3)) - k(3 * S)
LOWER = [list(w) for w in Ck.LOWER]
CAP = [list(w) for w in Ck.CAP]


def atoms(i, j):
    tb = C.hull_table(7, [LOWER[i], CAP[j]])
    return C.table_atoms(FACTORS + [Q0], [], pt, [7, 8], tb), tb


def crosscheck():
    assert len(FACTORS) == 28
    for a, b in zip(FACTORS, Ck.FACTORS):
        assert C.same_poly(a, b)
    assert C.same_poly(Q0, Ck.costs((0, 0))[0])
    for case in Ck.CASES:
        (_, idx), tb = atoms(*case)
        ck = Ck.cost_specs(case)
        assert {(t, sg == 1) for t, sg, _ in ck} <= set(tb), case


def main():
    crosscheck()
    data = json.loads((ROOT / 'docs' / 'proof' / 'nine' / 'c1_one_lower_right_top_triangle_certificates.json').read_text())
    certs = data['certificates']
    DATA.mkdir(parents=True, exist_ok=True)
    chosen = {}
    for cert in certs:
        for case in sorted(Ck.applicability(cert)):
            chosen.setdefault(case, cert)
    assert set(chosen) == set(Ck.CASES)
    total = 0
    rows = []
    for case in sorted(chosen):
        cert = chosen[case]
        (atl, idx), tb = atoms(*case)
        src = Ck.cost_specs(tuple(cert['case']))

        def qmap(qi):
            if qi == 0:
                return 28, F(0)
            t, sg, b = src[qi - 1]
            li, lb = idx[(t, sg == 1)]
            return li, lb - b
        terms = C.convert(cert, qmap)
        W = certlib.integer_weights(atl, terms)
        assert certlib.check(atl, W), case
        name = 'c%d%d.txt' % case
        certlib.write_terms(DATA / name, W)
        total += len(W)
        rows.append((case, name, len(W)))
    print('exported %d cells, %d terms' % (len(rows), total))
    lines = ['module', '', 'public import Heilbronn.Nine.C1.OneLower.RightTopTriangleModel',
             'public import Heilbronn.Common.DataReader', '',
             '/-! # The 25 right-top-triangle cells (generated by '
             '`scripts/nine/c1_one_lower_b/right_top_triangle.py`)', '',
             'Kernel checks of the certificates of '
             '`docs/proof/nine/c1_one_lower_right_top_triangle_certificates.json` (%d terms over the 25 cells, '
             'each certificate converted to the atoms of its cell). -/' % total, '',
             '@[expose] public section', '',
             'namespace Heilbronn.Nine.C1OneLowerRightTopTriangle.Model', '', 'open Cover', '']
    for case, name, _ in rows:
        lines += ['/-- The certificate of the cell %s. -/' % (case,),
                  'noncomputable def tree%d%d : Cover.Tree C1ZeroLower.Model.Split :=' % case,
                  '  .cert (term_rows%% "../../../../data/nine/c1_one_lower_rtt/%s")' % name, '']
    lines += ['/-- All the cells with their trees. -/',
              'noncomputable def allCases : List ((ℕ × ℕ) × Cover.Tree C1ZeroLower.Model.Split) :=',
              '  [' + ',\n    '.join('((%d, %d), tree%d%d)' % (c + c) for c, _, _ in rows) + ']', '',
              'theorem allCases_ok : allCases.all (fun p => checkTree (spec p.1.1 p.1.2) [] p.2) = true := by',
              '  decide +kernel', '',
              'theorem allCases_keys : allCases.map Prod.fst = (List.range 5).flatMap fun i => (List.range 5).map fun j => (i, j) := by',
              '  decide +kernel', '',
              'end Heilbronn.Nine.C1OneLowerRightTopTriangle.Model', '']
    (ROOT / 'Heilbronn' / 'Nine' / 'C1' / 'OneLower' / 'RightTopTriangleTrees.lean').write_text('\n'.join(lines))
    print('\n'.join(certlib.lean(a) for a in FACTORS))


if __name__ == '__main__':
    main()
