"""Generate Lean proofs of the hull triangle signs `0 ≤ sarea (V i) (V j) (V k)` from a sign
structure, by LP-found linarith hints (signlp.hints), with one case split when needed."""
import sys
from itertools import combinations
from pathlib import Path
import sympy as sp
sys.path.insert(0, str(Path(__file__).resolve().parent))
from signlp import hints  # noqa: E402


def sarea(p, q, r):
    return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])


def lean_e(e):
    s = str(e).replace('**', '^')
    return s if (' ' not in s and not s.startswith('-')) else '(%s)' % s


def lean_pt(p):
    return '(%s, %s)' % (lean_e(p[0]), lean_e(p[1]))


def prove(tgt, basics, gens, splits):
    """Lean tactic lines proving `0 ≤ tgt` (after `simp only [sarea]`)."""
    for deg in (2, 3):
        hs = hints(tgt, basics, gens, deg=deg, prefix='')
        if hs is not None:
            return ['  linarith [%s]' % ', '.join(hs)]
    for (u, w) in splits:
        b1 = basics + [('hs', w - u)]
        b2 = basics + [('hs', u - w)]
        r1 = hints(tgt, b1, gens, deg=3, prefix='')
        r2 = hints(tgt, b2, gens, deg=3, prefix='')
        if r1 is not None and r2 is not None:
            return ['  rcases le_total %s %s with hs | hs' % (lean_e(u), lean_e(w)),
                    '  · replace hs : 0 ≤ %s - %s := sub_nonneg.2 hs' % (lean_e(w), lean_e(u)),
                    '    linarith [%s]' % ', '.join(r1),
                    '  · replace hs : 0 ≤ %s - %s := sub_nonneg.2 hs' % (lean_e(u), lean_e(w)),
                    '    linarith [%s]' % ', '.join(r2)]
    return None


def gen(struct, args, basics, verts, gens, splits=(), n_label='t', triples=None):
    """struct: Lean structure name; args: its argument string; basics: [(field, expr)];
    verts: list of sympy point pairs (the hull, ccw)."""
    basics = [('H.' + n, e) for n, e in basics]
    out = []
    names = {}
    for (i, j, k) in (triples or combinations(range(len(verts)), 3)):
        tgt = sarea(verts[i], verts[j], verts[k])
        lines = prove(tgt, basics, gens, splits)
        assert lines is not None, (i, j, k)
        nm = '%s%d%d%d' % (n_label, i, j, k)
        names[(i, j, k)] = nm
        out.append('theorem %s.%s (H : %s %s) :\n    0 ≤ sarea %s %s %s := by\n'
                   '  simp only [sarea]\n%s\n' % (
                       struct, nm, struct, args, lean_pt(verts[i]), lean_pt(verts[j]),
                       lean_pt(verts[k]), '\n'.join(lines)))
    return '\n'.join(out), names


def module(modname, ns, docline, struct, args_decl, args, basics, verts, gens, splits, vname,
           strict_t='8 / 73'):
    """A complete Lean module: the sign structure, the triangle lemmas, the polygon `vname` and
    its strict convexity from the areas."""
    from itertools import combinations as comb
    body, names = gen(struct, args, basics, verts, gens, splits)
    fields = '\n'.join('  %s : 0 ≤ %s' % (n, lean_e(e).strip('()') if False else str(e).replace('**', '^'))
                       for n, e in basics)
    pts = ', '.join(lean_pt(p) for p in verts)
    nv = len(verts)
    bullets = '\n'.join('  · exact H.%s' % names[t] for t in comb(range(nv), 3))
    return '''module

public import Heilbronn.Nine.SixBoundary.SixBCommon

/-! # %s

Generated by `scripts/nine/six_radial/hull.py`: the hull triangles are nonnegative linear
combinations of products of the sign data `%s` (linarith hints found by linear programming); the
least area makes them strictly positive. -/

@[expose] public section

namespace %s

open SixRadial SixBoundary

/-- The sign data of the hull. -/
structure %s %s : Prop where
%s

/-- The hull polygon. -/
def %s %s : Fin %d → Point :=
  ![%s]

variable %s

%s
/-- The hull is strictly convex when every hull triangle has doubled area at least `%s`. -/
theorem %s.convex (H : %s %s)
    (hs : ∀ i j k : Fin %d, i < j → j < k →
      (%s : ℝ) ≤ |sarea (%s %s i) (%s %s j) (%s %s k)|) :
    IsConvexCCW (%s %s) := by
  intro i j k hij hjk
  refine pos_of_nonneg_of_le_abs (by norm_num) ?_ (hs i j k hij hjk)
  fin_cases i <;> fin_cases j <;> simp only [Fin.reduceFinMk, Fin.reduceLT, Fin.isValue] at hij ⊢ <;>
    fin_cases k <;> simp only [Fin.reduceFinMk, Fin.reduceLT, Fin.isValue] at hjk ⊢
%s

end %s
''' % (docline, struct, ns, struct, args_decl, fields, vname, args_decl, nv, pts, args_decl, body,
       strict_t, struct, struct, args, nv, strict_t, vname, args, vname, args, vname, args, vname,
       args, bullets, ns)
