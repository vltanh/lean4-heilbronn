#!/usr/bin/env python3
"""Export hand/c1_one_lower_eight_hull_certificates.json for Lean.

Mirror of Heilbronn/C1/OneLower/EightHullModel.lean. Checks that the Lean atoms (factors and
the 84 table costs) equal the checker's FACTORS and costs as polynomials, converts the twelve
certificates to integer weights for `Cert.check`, writes data/c1_one_lower_eight_hull/*.txt and
the Lean module Heilbronn/C1/OneLower/EightHullCerts.lean.
"""
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from common import (ROOT, N, v, k, SQ, LEX, table_atoms, convert, same_poly,  # noqa: E402
                    checker_poly, certlib)
import check_c1_one_lower_eight_hull as Ck  # noqa: E402

DATA = ROOT / 'data' / 'c1_one_lower_eight_hull'
LEAN = ROOT / 'Heilbronn' / 'C1' / 'OneLower' / 'EightHullCerts.lean'


def pt_one(i):
    return {0: (N(0), N(0)), 1: (v(1), N(0)), 2: (v(4), v(5)), 3: (N(1), v(2)),
            4: (v(6), v(7)), 5: (v(3), N(1)), 6: (v(8), v(9)), 7: (N(0), v(0)),
            8: (v(10), v(11))}[i]


def pt_two(i):
    return {0: (N(0), N(0)), 1: (v(1), N(0)), 2: (v(4), v(5)), 3: (N(1), v(2)),
            4: (v(6), v(7)), 5: (v(8), v(9)), 6: (v(3), N(1)), 7: (N(0), v(0)),
            8: (v(10), v(11))}[i]


one = N(1)
FACTORS_ONE = [
    v(0) - k(F(32, 73)), k(F(6, 7)) - v(0), v(1) - k(F(32, 73)), k(F(6, 7)) - v(1),
    v(2) - k(F(32, 73)), v(0) - v(2), v(3) - k(F(32, 73)), v(1) - v(3), v(2) - v(3),
    v(4) - v(1) - k(F(28, 219)), one - v(4), v(5) - k(F(28, 219)), v(2) - v(5) - k(F(8, 41)),
    v(6) - v(3) - k(F(8, 41)), v(7) - v(2) - k(F(8, 41)), one - v(6), one - v(7),
    v(8) - k(F(28, 219)), v(3) - v(8) - k(F(8, 41)), v(9) - v(0) - k(F(28, 219)), one - v(9),
    v(10) - k(F(28, 219)), v(11) - k(F(28, 219)), v(1) - v(10) - k(F(56, 219)),
    v(0) - v(11) - k(F(56, 219)), one - v(10) - v(11) - k(F(8, 73))]
FACTORS_TWO = [
    v(0) - k(F(384, 803)), one - v(0), v(1) - k(F(24, 73)), k(F(11, 16)) - v(1),
    v(2) - k(F(32, 73)), k(F(33, 65)) - v(2), v(3) - k(F(8, 73)), k(F(17, 50)) - v(3),
    v(0) - v(2), v(1) - v(3),
    v(4) - v(1) - k(F(520, 2409)), one - v(4), v(5) - k(F(128, 803)), v(2) - v(5) - k(F(8, 49)),
    v(6) - v(3) - k(F(8, 41)), one - v(6), v(7) - v(2) - k(F(8, 65)), one - v(7),
    v(8) - v(3) - k(F(8, 41)), one - v(8), v(9) - v(2) - k(F(8, 65)), one - v(9),
    v(6) - v(8) - k(F(8, 73)), v(9) - v(7) - k(F(8, 73)), v(10) - k(F(8, 73)),
    v(11) - k(F(128, 803)), v(1) - v(10) - k(F(16, 73)), v(0) - v(11) - k(F(256, 803)),
    one - v(10) - v(11) - k(F(8, 73))]

OCT_WORDS = [[1, 6, 6, 5, 4, 3, 2, 1], [2, 6, 5, 5, 4, 3, 2, 1], [3, 6, 5, 4, 4, 3, 2, 1],
             [4, 6, 5, 4, 3, 3, 2, 1], [5, 6, 5, 4, 3, 2, 2, 1], [6, 6, 5, 4, 3, 2, 1, 1]]


def positive(w, i, j):
    return (j + 8 - i) % 8 <= w[i]


def table(w):
    return [(t, True if t[2] < 8 else positive(w, t[0], t[1])) for t in LEX]


MODES = {'one_each': (False, pt_one, FACTORS_ONE), 'two_top': (True, pt_two, FACTORS_TWO)}


def main():
    data = json.loads((ROOT / 'hand' / 'c1_one_lower_eight_hull_certificates.json').read_text())
    assert [list(w) for w in Ck.words()] == OCT_WORDS
    DATA.mkdir(parents=True, exist_ok=True)
    thms = []
    total = 0
    for cert in data['certificates']:
        mode, wi = cert['mode'], cert['word_index']
        m, pt, fac = MODES[mode]
        w = OCT_WORDS[wi]
        assert cert['word'] == w
        # factors agree with the checker
        assert len(fac) == len(Ck.FACTORS[mode])
        for e, p in zip(fac, Ck.FACTORS[mode]):
            assert certlib.rat_value_poly(e) == checker_poly(p)
        atoms, index = table_atoms(fac, [], pt, [8], table(w))
        nf = len(fac)
        qs = Ck.costs(mode, tuple(w))
        assert len(qs) == 84
        for qi, p in enumerate(qs):
            assert certlib.rat_value_poly(atoms[nf + qi]) == checker_poly(p), (mode, wi, qi)
        terms = convert(cert, nf, lambda qi: (nf + qi, 0))
        W = certlib.integer_weights(atoms, terms)
        assert certlib.check(atoms, W), (mode, wi)
        name = '%s_%d.txt' % ('two' if m else 'one', wi)
        certlib.write_terms(DATA / name, W)
        total += len(W)
        thms.append((m, wi, name))
    print('eight hull: %d certificates, %d terms' % (len(thms), total))
    lines = ['module', '', 'public import Heilbronn.C1.OneLower.EightHullModel',
             'public import Heilbronn.Common.DataReader', '',
             '/-! # The twelve eight-hull certificates (generated by '
             '`scripts/c1_one_lower/eight_hull.py`)', '',
             'Kernel checks of the certificates of `hand/c1_one_lower_eight_hull_certificates.json`'
             ' (%d terms), one per mode and octagon word. -/' % total, '',
             '@[expose] public section', '', 'namespace Heilbronn.C1OneLowerEightHull.Model', '',
             'open Cover C1OneLower', '']
    for m, wi, name in thms:
        tag = 'two' if m else 'one'
        lines += ['/-- The certificate of mode `%s`, word %d. -/' % ('two_top' if m else 'one_each', wi),
                  'noncomputable def tree_%s_%d : Cover.Tree C1ZeroLower.Model.Split :=' % (tag, wi),
                  '  .cert (term_rows%% "../../../data/c1_one_lower_eight_hull/%s")' % name, '',
                  'theorem tree_%s_%d_ok : checkTree (spec %s (octWords.getD %d [])) [] tree_%s_%d = '
                  'true := by' % (tag, wi, 'true' if m else 'false', wi, tag, wi),
                  '  decide +kernel', '']
    lines += ['end Heilbronn.C1OneLowerEightHull.Model', '']
    LEAN.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
