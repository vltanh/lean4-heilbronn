#!/usr/bin/env python3
"""Export the opposite-cap certificate package (hand/six_boundary_opposite_cap_certificates.json).

1. Builds the word cover of model.py (splits on the radial word entries of O, vertex order
   ORDER, branches filtered by consistency with the known signs) and checks that its leaves are
   exactly the 15 words of the hand checker.
2. Converts each certificate to integer weights on the Lean atom list
   `factors ++ [delta] ++ costs` (the `left` / `low` certificates on that list followed by the
   branch factor `c - e_x` / `h - g_y`), checking at its leaf that every cost of the checker has
   the sign and bound of the Lean model.
3. Writes data/six_opposite_cap/*.txt and Heilbronn/Six/OppositeCapTrees.lean.
"""
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / 'hand'))
sys.path.insert(0, str(ROOT / 'scripts'))
import model as M  # noqa: E402
import certlib  # noqa: E402
from certlib import v  # noqa: E402
import check_six_boundary_opposite_cap as Ck  # noqa: E402

DATA = ROOT / 'data' / 'six_opposite_cap'
ORDER = [4, 5, 0, 1, 2, 3, 6, 7]
SHARP = (4, 3, 3, 2, 3, 4, 5, 4)


def branches(fs, i):
    tb = M.base() + fs
    out = []
    for val in range(1, 7):
        b = M.branch(i, val)
        if all(M.lookup(tb, f[0]) in (None, f[1]) for f in b):
            out.append((val, b))
    return out


def build(fs, assigned):
    if len(assigned) == 8:
        return ('word', tuple(assigned[i] for i in range(8)))
    i = ORDER[len(assigned)]
    kids = []
    for val, b in branches(fs, i):
        a = dict(assigned)
        a[i] = val
        kids.append((val, b, build(fs + b, a)))
    return ('node', i, kids)


def leaves(t, fs=()):
    if t[0] == 'word':
        yield t[1], list(fs)
    else:
        for val, b, c in t[2]:
            yield from leaves(c, tuple(fs) + tuple(b))


def cert_terms(cert, fs):
    atoms = M.atoms(fs)
    nf = len(M.factors())
    extra = None
    if cert['branch'] == 'left':
        extra = v(3) - v(6)
    elif cert['branch'] == 'low':
        extra = v(1) - v(9)
    if extra is not None:
        atoms = atoms + [extra]
    xi = len(atoms) - 1

    def fidx(i):
        return xi if i == nf else i
    terms = []
    for term in cert['terms']:
        if term[0] == 'f':
            terms.append((F(term[2], cert['scale']), [fidx(i) for i in term[1]]))
        else:
            _, i, j, w = term
            idx = nf if i == 84 else nf + 1 + i
            terms.append((F(w, cert['scale']), [idx] + ([fidx(j)] if j >= 0 else [])))
    return atoms, terms


def main():
    data = json.loads((ROOT / 'hand' / 'six_boundary_opposite_cap_certificates.json').read_text())
    certs = data['certificates']
    tree = build([], {})
    lv = list(leaves(tree))
    words = [w for w, _ in lv]
    assert sorted(words) == sorted(Ck.WORDS), (sorted(words), sorted(Ck.WORDS))
    # every leaf: the strengthened bounds and signs agree with the checker
    for w, fs in lv:
        tb = M.base() + fs
        for t in M.LEX:
            (i, j, kk) = t
            sg = 1 if kk < 8 or j - i <= w[i] else -1
            thr = 3 * M.S if kk < 8 and Ck.inside(w, t) else M.S
            s2 = M.lookup(tb, t)
            assert s2 is not None and (1 if s2 else -1) == sg, (w, t)
            assert M.bnd(len(M.inside_list(tb, [8], (t, s2)))) == thr, (w, t)
    DATA.mkdir(parents=True, exist_ok=True)
    leaf_fs = dict(lv)
    out = {}
    total = 0
    for c in certs:
        w = tuple(c['word'])
        atoms, terms = cert_terms(c, leaf_fs[w])
        W = certlib.integer_weights(atoms, terms)
        assert certlib.check(atoms, W), (w, c['branch'])
        name = 'w%s_%s' % (''.join(map(str, w)), c['branch'])
        certlib.write_terms(DATA / (name + '.txt'), W)
        out[(w, c['branch'])] = (name, len(W))
        total += len(W)
    print('certificates', len(out), 'terms', total)
    return tree, out


def lean_tree(t, out):
    if t[0] == 'word':
        if t[1] == SHARP:
            return '.closed 1'
        name, _ = out[(t[1], 'whole')]
        return '.cert (term_rows%% "../../../data/six_opposite_cap/%s.txt")' % name
    return '.node (.vertex %d) [%s]' % (t[1], ', '.join(lean_tree(c, out) for _, _, c in t[2]))


def terms_of(t, out):
    if t[0] == 'word':
        return 0 if t[1] == SHARP else out[(t[1], 'whole')][1]
    return sum(terms_of(c, out) for _, _, c in t[2])


def facts_lean(path):
    s = '[]'
    for (i, val) in path:
        s = '(%s ++ branchFacts %d %d)' % (s, i, val)
    return s


HEAD = """module

public import Heilbronn.Six.OppositeCapModel
public import Heilbronn.Common.DataReader

/-! # Opposite-cap cover, part %d (generated by `scripts/six_opposite_cap/export.py`)

%s -/

@[expose] public section

namespace Heilbronn.SixBoundaryOppositeCapCompletion.Trees

open Cert Cert.Expr Cover Model

"""

LIMIT = 300
PARTS = [[2], [3, 4], [5, 6]]


def emit(t, path, name, out, lines):
    """Theorems `name_ok : checkTree spec (facts of path) t = true`, split into subtrees of at most
    LIMIT certificate terms (a node is assembled from its children by `checkTree_node`)."""
    if t[0] == 'word' or terms_of(t, out) <= LIMIT:
        lines.append('/-- The subtree below `%s` (%d terms). -/\nnoncomputable def %s : '
                     'Cover.Tree Split :=\n  %s\n\n' % (' ∧ '.join('r_%d = %d' % q for q in path),
                                                        terms_of(t, out), name, lean_tree(t, out)))
        lines.append('theorem %s_ok : checkTree spec %s %s = true := by\n  decide +kernel\n\n'
                     % (name, facts_lean(path), name))
        return
    kids = []
    for val, b, c in t[2]:
        cn = '%s_%d' % (name, val)
        emit(c, path + [(t[1], val)], cn, out, lines)
        kids.append((val, cn))
    lines.append('/-- The subtree below `%s`. -/\nnoncomputable def %s : Cover.Tree Split :=\n'
                 '  .node (.vertex %d) [%s]\n\n' % (' ∧ '.join('r_%d = %d' % q for q in path), name,
                                                    t[1], ', '.join(cn for _, cn in kids)))
    lines.append('theorem %s_br : branches %s (.vertex %d) = [%s] := by decide +kernel\n\n'
                 % (name, facts_lean(path), t[1],
                    ', '.join('branchFacts %d %d' % (t[1], v) for v, _ in kids)))
    lines.append('theorem %s_ok : checkTree spec %s %s = true := by\n'
                 '  rw [%s, checkTree_node, show spec.branches = branches from rfl, %s_br]\n'
                 '  simp only [checkChildren_cons, checkChildren_nil, Bool.and_true, Bool.and_eq_true]\n'
                 '  exact ⟨%s⟩\n\n' % (name, facts_lean(path), name, name, name,
                                        ', '.join('%s_ok' % cn for _, cn in kids)))


def write_lean(tree, out):
    i0 = tree[1]
    LEAN = ROOT / 'Heilbronn' / 'Six' / 'OppositeCapTrees'
    LEAN.mkdir(parents=True, exist_ok=True)
    kids = {v0: c0 for v0, b0, c0 in tree[2]}
    assert sorted(kids) == sorted(sum(PARTS, []))
    for pi, part in enumerate(PARTS):
        lines = [HEAD % (pi, 'Subtrees of the word cover of `O` (`hand/six_boundary_opposite_cap_'
                         'certificates.json`) below `r_%d = %s`, checked by the kernel.'
                         % (i0, ', '.join(map(str, part))))]
        for v0 in part:
            emit(kids[v0], [(i0, v0)], 'sub_%d' % v0, out, lines)
        lines.append('end Heilbronn.SixBoundaryOppositeCapCompletion.Trees\n')
        (LEAN / ('Part%d.lean' % pi)).write_text(''.join(lines))
    # the sharp-word facts and the two height certificates
    path = []
    t = tree
    while t[0] != 'word':
        for val, b, c in t[2]:
            if any(w == SHARP for w, _ in leaves(c)):
                path.append((t[1], val))
                t = c
                break
    lines = [HEAD % (len(PARTS), 'The two height certificates `left` (`e_x ≤ c`) and `low` '
                     '(`g_y ≤ h`) of the sharp word, on its atoms.')]
    lines.append('/-- The facts of the sharp word `(4, 3, 3, 2, 3, 4, 5, 4)` along the cover. -/\n'
                 'def sharpFacts : List SFact :=\n  %s\n\n' % facts_lean(path))
    for br, ex, desc in [('left', 'v 3 - v 6', 'c - e_x'), ('low', 'v 1 - v 9', 'h - g_y')]:
        name, n = out[(SHARP, br)]
        lines.append('/-- The `%s` certificate (%d terms): the atoms of the sharp word and the branch '
                     'factor `%s`. -/\ntheorem %s_ok : Cert.check (atoms sharpFacts ++ [%s])\n'
                     '    (term_rows%% "../../../data/six_opposite_cap/%s.txt") = true := by\n'
                     '  decide +kernel\n\n' % (br, n, desc, br, ex, name))
    lines.append('end Heilbronn.SixBoundaryOppositeCapCompletion.Trees\n')
    (LEAN / ('Part%d.lean' % len(PARTS))).write_text(''.join(lines))
    # the root
    imports = ''.join('public import Heilbronn.Six.OppositeCapTrees.Part%d\n' % i
                      for i in range(len(PARTS) + 1))
    names = ['sub_%d' % v0 for v0, _, _ in tree[2]]
    lines = ['module\n\n', imports,
             '\n/-! # Opposite-cap cover: the root check (generated by '
             '`scripts/six_opposite_cap/export.py`)\n\n'
             'The word cover of `O` (%d certificate terms), split first at `V_%d`; the subtrees and '
             'the two height certificates are checked in the parts. -/\n\n'
             '@[expose] public section\n\nnamespace Heilbronn.SixBoundaryOppositeCapCompletion.Trees\n\n'
             'open Cert Cert.Expr Cover Model\n\n' % (terms_of(tree, out), i0)]
    lines.append('/-- The complete word cover. -/\nnoncomputable def tree : Cover.Tree Split :=\n'
                 '  .node (.vertex %d) [%s]\n\n' % (i0, ', '.join(names)))
    lines.append('theorem branches_root : branches [] (.vertex %d) = [%s] := by decide +kernel\n\n'
                 % (i0, ', '.join('branchFacts %d %d' % (i0, v0) for v0, _, _ in tree[2])))
    lines.append('theorem tree_ok : checkTree spec [] tree = true := by\n'
                 '  rw [tree, checkTree_node, show spec.branches = branches from rfl, branches_root]\n'
                 '  simp only [checkChildren_cons, checkChildren_nil, Bool.and_true, Bool.and_eq_true]\n'
                 '  exact ⟨%s⟩\n\n' % ', '.join('%s_ok' % n for n in names))
    lines.append('end Heilbronn.SixBoundaryOppositeCapCompletion.Trees\n')
    (ROOT / 'Heilbronn' / 'Six' / 'OppositeCapTrees.lean').write_text(''.join(lines))
    print('root vertex', i0, 'children', [(v0, terms_of(c0, out)) for v0, _, c0 in tree[2]])
    print('sharp path', path)


if __name__ == '__main__':
    tree, out = main()
    write_lean(tree, out)
