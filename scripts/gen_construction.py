#!/usr/bin/env python3
"""Generate Heilbronn/Construction/Areas.lean: one lemma per triangle of the optimal
configuration, with the sign of its signed area computed exactly in Q(sqrt 65)."""
import sympy as sp
from itertools import combinations
s = sp.Symbol('s')  # sqrt 65
p = (15 - s) / 40
A0 = (9 * s - 55) / 320
names = 'ABCDEFGHO'
P = [(0, 4*p - sp.Rational(1, 2)), (p, 0), (1 - 3*p/2, 0), (1, 3*p/2), (1, 1 - p),
     (sp.Rational(3, 2) - 4*p, 1), (p, 1), (0, 1 - p), (1 - 2*p, 2*p)]
def red(e):
    e = sp.expand(e)
    return sp.expand(e.subs(s**2, 65))
out = []
tight = []
for i, j, k in combinations(range(9), 3):
    (x1, y1), (x2, y2), (x3, y3) = P[i], P[j], P[k]
    sa = red((x2 - x1)*(y3 - y1) - (y2 - y1)*(x3 - x1))
    v = float(sa.subs(s, sp.sqrt(65)))
    sign = 1 if v > 0 else -1
    gap = red(sign*sa - 2*A0)
    g = float(gap.subs(s, sp.sqrt(65)))
    assert g > -1e-12, (i, j, k, g)
    if abs(g) < 1e-12:
        assert gap == 0, (i, j, k, gap)
        tight.append(names[i] + names[j] + names[k])
    out.append((i, j, k, sign))
lines = ['module', '', 'public import Heilbronn.Common.Basic', '',
 '/-!', '# The 84 triangle areas of the optimal configuration', '',
 'One lemma for each triangle `i < j < k` of `optimalConfiguration`: its doubled signed area is at',
 'least `2 A₀` or at most `-2 A₀`, with `A₀ = (9√65 - 55)/320`. Each signed area is `a + b√65`',
 'with rational `a, b`, so it is decided by `√65 ∈ (8.0622, 8.0623)`. Equality holds for the',
 'eleven triangles ' + ', '.join(tight) + ' (HAND_PROOF.md, appendix).', '',
 'Generated by `scripts/gen_construction.py`.', '-/', '',
 '@[expose] public section', '', 'noncomputable section', 'namespace Heilbronn.Construction', '',
 'theorem sqrt65_sq : Real.sqrt 65 ^ 2 = 65 := Real.sq_sqrt (by norm_num)', '',
 'theorem sqrt65_gt : (8.0622 : ℝ) < Real.sqrt 65 := by',
 '  rw [Real.lt_sqrt (by norm_num)]; norm_num', '',
 'theorem sqrt65_lt : Real.sqrt 65 < 8.0623 := by',
 '  rw [Real.sqrt_lt\' (by norm_num)]; norm_num', '']
for i, j, k, sign in out:
    nm = 'area_%s%s%s' % (names[i], names[j], names[k])
    rel = '2 * ((9 * Real.sqrt 65 - 55) / 320) ≤ sarea' if sign > 0 else 'sarea'
    stmt = ('theorem %s :\n    %s (optimalConfiguration %d) (optimalConfiguration %d)\n      (optimalConfiguration %d)%s := by'
            % (nm, rel, i, j, k, '' if sign > 0 else ' ≤ -(2 * ((9 * Real.sqrt 65 - 55) / 320))'))
    lines += [stmt,
              '  simp only [optimalConfiguration, sarea, p₀, Matrix.cons_val]',
              '  nlinarith [sqrt65_sq, sqrt65_gt, sqrt65_lt]', '']
lines += ['/-- Every triangle of the optimal configuration has area at least `A₀`. -/',
          'theorem le_area (i j k : Fin 9) (hij : i < j) (hjk : j < k) :',
          '    (9 * Real.sqrt 65 - 55) / 320 ≤',
          '      triangleArea (optimalConfiguration i) (optimalConfiguration j) (optimalConfiguration k) := by',
          '  have hA : (0 : ℝ) < (9 * Real.sqrt 65 - 55) / 320 := by linarith [sqrt65_gt]',
          '  fin_cases i <;> fin_cases j <;> fin_cases k <;>',
          '    try (first | (exact absurd hij (by decide)) | (exact absurd hjk (by decide)))']
seq = []
for i, j, k, sign in out:
    nm = 'area_%s%s%s' % (names[i], names[j], names[k])
    lem = 'le_triangleArea_of_pos' if sign > 0 else 'le_triangleArea_of_neg'
    pos = ('(lt_of_lt_of_le (by linarith [hA]) %s)' % nm) if sign > 0 else ('(lt_of_le_of_lt %s (by linarith [hA]))' % nm)
    seq.append('  · exact (%s hA %s).2 %s' % (lem, pos, nm))
lines += seq
lines += ['', 'end Heilbronn.Construction', '']
open('Heilbronn/Construction/Areas.lean', 'w').write('\n'.join(lines))
print(len(out), 'triangles;', len(tight), 'tight:', tight)
