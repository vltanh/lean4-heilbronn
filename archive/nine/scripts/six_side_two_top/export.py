#!/usr/bin/env python3
"""Export docs/proof/nine/six_boundary_side_two_top_certificates.json to the radial cover of
Heilbronn/Nine/SixBoundary/SideTwoTopModel.lean (mirror: scripts/nine/six_radial/radial.py).

Points 0..8 = A, B, C, X, D, E, F, H, O; variables 0..11 = a, h, b, c, d, f, x, y, ex, ey, ox, oy.
"""
import json
import sys
from fractions import Fraction as F
from itertools import permutations
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
sys.path.insert(0, str(ROOT / 'scripts' / 'nine' / 'six_radial'))
import certlib  # noqa: E402
import radial as R  # noqa: E402
from certlib import v, k  # noqa: E402

N0 = R.N0
S = F(8, 73)
PT = {0: (N0(0), v(0)), 1: (v(2), N0(0)), 2: (v(3), N0(0)), 3: (v(6), v(7)), 4: (N0(1), v(4)),
      5: (v(8), v(9)), 6: (v(5), N0(1)), 7: (N0(0), v(1)), 8: (v(10), v(11))}


def pt(i):
    return PT.get(i, (N0(0), N0(0)))


ONE = N0(1)
FACTORS = [v(0) - k(F(1, 7)), v(2) - k(F(1, 8)), v(1) - k(F(1, 2)), v(3) - k(4 * S), ONE - v(1),
           k(1 - S) - v(3), v(4) - v(0), v(1) - v(4), v(5) - v(2), v(3) - v(5),
           v(4) - k(F(1, 2)), k(F(5, 8)) - v(4), v(1) - v(0) - k(S), v(3) - v(2) - k(S),
           v(6) - v(3) - k(S), ONE - v(6), v(7) - k(F(1, 7)), v(4) - v(7) - k(F(7, 36)),
           k(1 - 6 * S) - v(5), v(8) - v(5) - k(6 * S), v(9) - v(4) - k(3 * S), ONE - v(8),
           ONE - v(9), v(10) - v(5) - k(2 * S), v(11) - v(4) - k(F(1, 8)), k(1 - S) - v(10),
           k(1 - S) - v(11)]
BASE = [(t, True) for t in R.lex_triples(8)] + [((4, 6, 8), False)]


def bnd(m):
    return S if m == 0 else 3 * S


def extra(tb):
    return [(ONE - v(4)) * (ONE - v(5)) - k(3 * S)]


PKG = R.Pkg(8, 9, pt, FACTORS, BASE, bnd, [8], extra)

LEAN_FACTORS = ',\n    '.join(certlib.lean(e) for e in FACTORS)


def best_order(p):
    best = None
    for order in permutations(range(8)):
        if order[0] != 4:
            continue
        t = PKG.enum_tree(p, list(order))
        c = R.count_nodes(t)
        if best is None or c < best[0]:
            best = (c, order, t)
    return best


def main():
    data = json.loads((ROOT / 'docs' / 'proof' / 'nine' / 'six_boundary_side_two_top_certificates.json').read_text())
    certs = data['certificates']
    c, order, tree = best_order(8)
    words = sorted(R.tree_words(tree))
    assert len(words) == 6, words
    print('enumeration nodes', c, 'order', order)
    index = {w: i for i, w in enumerate(words)}
    nf = len(FACTORS)
    DATA = ROOT / 'data' / 'nine' / 'six_side_two_top'
    DATA.mkdir(parents=True, exist_ok=True)
    leaves = {}
    for cert in certs:
        w = tuple(cert['word'])
        i = index[w]
        fs = [('s', f) for f in R.word_facts(8, 8, list(w))]
        atoms = PKG.atoms(fs)
        off = PKG.offsets(fs)
        terms = []
        for term in cert['terms']:
            if term[0] == 'f':
                terms.append((F(term[2], cert['scale']), list(term[1])))
            else:
                _, qi, fi, wt = term
                qidx = off['t2'] + qi if qi < 84 else off['x'] + (qi - 84)
                terms.append((F(wt, cert['scale']), [qidx] + ([fi] if fi >= 0 else [])))
        W = certlib.integer_weights(atoms, terms)
        assert certlib.check(atoms, W), w
        certlib.write_terms(DATA / ('w%d.txt' % i), W)
        leaves[i] = len(W)
    print('leaves', leaves)
    return words, tree, index, leaves


HEAD = '''module

public import Heilbronn.Nine.SixBoundary.RadialCover
public import Heilbronn.Common.DataReader

/-! # The certificate model of the side/two-top package (`docs/proof/nine/SIX_BOUNDARY_SIDE_TWO_TOP.md`)

Generated by `scripts/nine/six_side_two_top/export.py` from
`docs/proof/nine/six_boundary_side_two_top_certificates.json` (checker
`docs/proof/nine/check_six_boundary_side_two_top.py`), in the generic form `Heilbronn.Nine.SixRadial`:

* points `0, …, 8` are `A, B, C, X, D, E, F, H, O` (the hull octagon and the inner cap point);
  variables `0, …, 11` are `a, h, b, c, d, f, x, y, e_x, e_y, o_x, o_y`;
* `factors`: the 27 affine factors (13); `base`: the 56 hull triangles and `[DFO] < 0`;
  `extra`: the cost `δ - 3s`;
* `enumTree`: the radial words of `O` (split on its entries, leaves closed by the six words);
* `tree i`: the certificate of the word `words[i]` (kernel-checked, one per theorem).
-/

@[expose] public section

namespace Heilbronn.Nine.SixBoundarySideTwoTop.Model

open Cert Cert.Expr Cover SixRadial

/-- The nine points as expressions. -/
def pt : ℕ → Expr × Expr
  | 0 => (0, v 0)
  | 1 => (v 2, 0)
  | 2 => (v 3, 0)
  | 3 => (v 6, v 7)
  | 4 => (1, v 4)
  | 5 => (v 8, v 9)
  | 6 => (v 5, 1)
  | 7 => (0, v 1)
  | 8 => (v 10, v 11)
  | _ => (0, 0)

/-- The 27 affine factors (13). -/
def factors : List Expr :=
  [%s]

/-- The hull triangles (positive) and `[DFO] < 0`. -/
def base : List SFact := (lexTriples 8).map (fun t => (t, true)) ++ [((4, 6, 8), false)]

/-- The occupancy bounds `s`, `3s`. -/
def bnd (m : ℕ) : ℚ := if m = 0 then 8 / 73 else 24 / 73

/-- The cost `δ - 3s`. -/
def extra (_ : List SFact) : List Expr := [(1 - v 4) * (1 - v 5) - k (24 / 73)]

/-- The package. -/
def pkg : Pkg := ⟨8, 9, pt, factors, base, bnd, [8], extra⟩

/-- The six words (16). -/
def words : List (List ℕ) :=
  %s

/-- The enumeration of the words of `O`. -/
def enumTree : Cover.Tree Split :=
  %s

theorem enum_ok : checkTree (pkg.spec (pkg.enumClosed 8 words)) [] enumTree = true := by
  tree_decide

/-- The initial facts of the word `words[i]`. -/
def leafFacts (i : ℕ) : List Fact := (wordFacts 8 8 (words.getD i [])).map Sum.inl

'''


def write_lean(words, tree, index, leaves):
    out = [HEAD % (LEAN_FACTORS, R.lean_words(words), R.lean_enum_tree(tree, index))]
    for i in range(len(words)):
        out.append('/-- The certificate of the word `%s` (%d terms). -/\n'
                   'noncomputable def tree%d : Cover.Tree Split :=\n'
                   '  .cert (term_rows%% "../../../data/nine/six_side_two_top/w%d.txt")\n\n'
                   'theorem ok%d : checkTree (pkg.spec Pkg.noClosed) (leafFacts %d) tree%d = true := by\n'
                   '  tree_decide\n\n' % (list(words[i]), leaves[i], i, i, i, i, i))
    out.append('theorem all_ok (i : ℕ) (hi : i < %d) :\n'
               '    ∃ T, checkTree (pkg.spec Pkg.noClosed) (leafFacts i) T = true := by\n'
               '  interval_cases i\n' % len(words))
    for i in range(len(words)):
        out.append('  · exact ⟨_, ok%d⟩\n' % i)
    out.append('\nend Heilbronn.Nine.SixBoundarySideTwoTop.Model\n')
    (ROOT / 'Heilbronn' / 'Nine' / 'SixBoundary' / 'SideTwoTopModel.lean').write_text(''.join(out))


if __name__ == '__main__':
    write_lean(*main())
